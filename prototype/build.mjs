// Dependency-free bundler: wraps engine/detector.js (ES module) into a classic
// content script that exposes a frozen FlashDetector global in the isolated world.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const here = dirname(fileURLToPath(import.meta.url));
const src = readFileSync(join(here, 'engine/detector.js'), 'utf8');

if (/^\s*import\b/m.test(src) || /\bimport\s*\(/.test(src)) throw new Error('detector must not import modules');
if (/\beval\s*\(|\bnew\s+Function\b|\bFunction\s*\(/.test(src)) throw new Error('dynamic code is forbidden');

const names = [];
const body = src.replace(/^export\s+(function|const)\s+([A-Za-z_$][\w$]*)/gm, (_, kind, name) => {
  names.push(name);
  return `${kind} ${name}`;
});
if (/^\s*export\b/m.test(body)) throw new Error('unsupported export form in detector.js');
if (!names.includes('createDetector')) throw new Error('createDetector export missing');

const out = `// GENERATED by prototype/build.mjs from engine/detector.js. Do not edit.
(() => {
'use strict';
${body}
Object.defineProperty(globalThis, 'FlashDetector', {
  value: Object.freeze({ ${names.join(', ')} }),
  writable: false, configurable: false, enumerable: false,
});
})();
`;

// Sanity check: the bundle runs as a classic script and exposes a working API.
const ctx = vm.createContext({});
vm.runInContext(out, ctx);
const probe = vm.runInContext(
  "FlashDetector.createDetector({ width: 1, height: 1 }).push({ t: 0, pixels: new Uint8ClampedArray(4), areaPx: 1 }).reason",
  ctx,
);
if (probe !== 'clear') {
  throw new Error('bundle self-check failed');
}

const target = join(here, 'extension/content-bundle.js');
writeFileSync(target, out);
console.log(`wrote ${target} (${out.length} bytes; exports: ${names.join(', ')})`);
